import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as k from './anatomy/iso-kit.mjs';

const base = {x: -106, y: -86, w: 212, d: 172, r: 7};
const P = k.fitProjection([...k.boxCorners(base,-17,0), ...k.boxCorners({x:-69,y:-64,w:125,d:133,r:0},43,66)], 580, 350, {pad: 36, azimuth: 42, elevation: 36});
const S = k.solidSvg, L = k.lineSvg;
const at = p => k.iso(p, P);
const slab = (x,y,w,d,z,h,tone='mid',r=1.5,lit=false) => S(k.slabOf({x,y,w,d,r},z,h,P,5,.6),{tone,lit});
const screws = (points,z) => L(points.map(([x,y])=>k.ring(x,y,1.5,z,P,12)).join(''),{tone:'lo'}) + k.dotsSvg(points.map(([x,y])=>at([x,y,z])),{size:.48});
const parts = [];
parts.push(`<path class="iso-halo" d="${k.haloOf(base,-17,10,P)}"/>`);
for (const [x,y] of k.corners(base,18).sort((a,b)=>k.depthOf([...a,0],P)-k.depthOf([...b,0],P))) parts.push(slab(x-7,y-7,14,14,-17,5,'lo',3));
parts.push(S(k.slabOf(base,-12,10,P,8,1.4),{tone:'mid',inner:L(k.sideSeam(base,-6,P,8),{tone:'faint'})}));
parts.push(S(k.slabOf(k.insetPlan(base,.8),-2,2,P,8,.6),{tone:'lo'}));
parts.push(L(k.planOutline(k.insetPlan(base,5),0,P),{tone:'faint'}));
parts.push(screws(k.corners(base,10),0));

function rail(y) {
  let out = slab(-83,y-5,154,12,0,4,'lo') + slab(-78,y-2,144,6,4,5,'mid',.6);
  for (const x of [-84,66]) out += slab(x,y-5,6,12,4,10) + screws([[x+3,y+1]],14);
  return out;
}
parts.push(rail(-59));
parts.push(slab(-70,-49,130,100,0,3,'lo',3));
parts.push(slab(-66,-45,122,92,3,3,'hi',2));
// One physical sample with flat inlays. Intensity is illustrative, not a result.
for (let col=0;col<8;col++) {
  let cells='';
  for (let row=0;row<8;row++) {
    const level = Math.round(28 + 165 * (0.5 + 0.5*Math.sin(col*.67+row*.47)));
    const d = k.planOutline({x:-62+col*14.4,y:-41+row*10.5,w:13.5,d:9.6,r:.5},6.1,P,3);
    cells += `<path class="sample-pixel" fill="rgb(${level},${level},${level})" d="${d}"/>`;
  }
  parts.push(`<g data-pixel-column="${col}">${cells}</g>`);
}
parts.push(rail(57));
parts.push(slab(-75,72,143,5,0,.7,'lo',.6));
const ticks=k.topTicks(-71,64,4,4,72,.7,[2,3.7],P);
parts.push(L(ticks.minor,{tone:'lo'}),L(ticks.major,{tone:'mid'}));
parts.push(slab(76,-45,17,49,0,8,'mid',2));
for (const y of [-35,-14]) {
  parts.push(slab(79,y,11,14,8,1,'lo',1));
  parts.push(slab(81,y+2,7,10,9,3,'hi',1));
}
for (let i=0;i<8;i++) parts.push(L(k.planOutline({x:77,y:15+i*4,w:15,d:1.8,r:.8},0,P,3),{tone:'lo'}));
parts.push(slab(-46,-77,66,10,0,.8,'lo',1));
parts.push(screws([[-42,-72],[16,-72]],.8));
parts.push(k.faceTextSvg(k.topMatrix([-34,-70],.8,P),'BLOCK / 08',{size:3,tone:'mid'}));

let bridge='';
for(const y of [-59,57]) {
  bridge += slab(-64,y-5,14,12,9,6,'mid',1);
  bridge += slab(-62,y-3,10,8,15,40,'mid',1);
  bridge += slab(-64,y-5,14,12,50,5,'hi',1);
  bridge += screws([[-59,y],[-55,y+3]],55);
}
bridge += slab(-64,-64,14,133,55,8,'hi',2);
bridge += L(k.planOutline({x:-61,y:-60,w:8,d:125,r:1},63,P),{tone:'faint'});
bridge += slab(-69,-9,24,27,45,10,'mid',2);
bridge += slab(-67,-7,20,23,43,2,'hi',1,true);
bridge += slab(-67,-7,20,23,63,3,'hi',2);
bridge += screws([[-64,-4],[-50,13]],66);
for(let i=0;i<4;i++) bridge += L(k.planOutline({x:-63,y:-1+i*3.7,w:12,d:1.5,r:.6},66,P,3),{tone:'lo'});
const vector=k.axisVector(P,[1,0,0]);
parts.push(`<g id="inspection-carriage" data-vector="${vector.join(',')}">${bridge}</g>`);
const svg=`<!-- Generated by tools/build-inspector.mjs; edit the generator. -->\n<svg class="iso-svg" viewBox="0 0 580 350" aria-hidden="true" focusable="false">${parts.join('\n')}</svg>\n`;
writeFileSync(fileURLToPath(new URL('../app/templates/inspector.svg',import.meta.url)),svg);
console.log(`Built inspection bench (${(svg.length/1024).toFixed(1)} KiB)`);
