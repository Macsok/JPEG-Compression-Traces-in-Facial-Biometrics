const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {JSDOM} = require('jsdom');
const html = fs.readFileSync('app/templates/index.html', 'utf8');
const scripts = ['theme', 'i18n', 'histogram', 'app'].map(name => fs.readFileSync(`app/static/${name}.js`, 'utf8'));
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
function create(saved, blockedStorage = false, savedTheme) {
  const dom = new JSDOM(html, {url: 'http://localhost:8000', runScripts: 'outside-only'});
  const w = dom.window;
  if (saved) w.localStorage.setItem('compression-language', saved);
  if (savedTheme) w.localStorage.setItem('compression-theme', savedTheme);
  if (blockedStorage) Object.defineProperty(w, 'localStorage', {get() { throw Error('Storage unavailable'); }});
  let resolveFirst, calls = 0;
  w.fetch = async url => {
    if (url === '/health') return {ok: true, json: async () => ({models_loaded: true, max_upload_mb: 64, max_image_pixels: 24000000})};
    calls++;
    if (calls === 1) await new Promise(resolve => { resolveFirst = resolve; });
    return calls === 1
      ? {ok: true, json: async () => ({success: true, format: 'PPM', confidence: 99.4, predicted_quality: 93.5, probabilities: {JFIF: .006, PPM: .994}, indicators: {psnr: 30.1}, width: 96, height: 80, elapsed_seconds: .123})}
      : {ok: false, status: 422, json: async () => ({success: false, error_code: 'small', error_params: {}})};
  };
  const context = dom.getInternalVMContext();
  scripts.forEach(source => vm.runInContext(source, context));
  const $ = id => w.document.getElementById(id);
  const change = language => $('language-' + language).click();
  return {dom, w, context, $, change, finish: () => resolveFirst(), calls: () => calls};
}
(async () => {
  const ui = create(); await tick();
  const {$, w, context, change} = ui;
  assert.equal(w.document.documentElement.lang, 'en');
  assert.equal(w.document.documentElement.dataset.theme, 'light');
  assert.equal($('theme-light').getAttribute('aria-pressed'), 'true');
  assert.equal($('language-en').getAttribute('aria-pressed'), 'true');
  assert.equal($('start').textContent, 'Start analysis');
  assert.equal($('server-status').textContent, '● Models ready');
  assert.equal($('progress').getAttribute('aria-label'), 'Analysis progress');
  assert.match(w.document.querySelector('footer').textContent, /generated using AI/);
  const dictionaries = JSON.parse(vm.runInContext('JSON.stringify(messages)', context));
  assert.deepEqual(Object.keys(dictionaries.en).sort(), Object.keys(dictionaries.pl).sort());
  for (const key of Object.keys(dictionaries.en)) {
    assert.deepEqual((dictionaries.en[key].match(/\{\w+\}/g) || []).sort(), (dictionaries.pl[key].match(/\{\w+\}/g) || []).sort(), key);
  }
  w.document.querySelectorAll('[data-i18n]').forEach(el => assert.ok(dictionaries.en[el.dataset.i18n], el.dataset.i18n));
  const files = [new w.File(['image'], 'sample.png'), new w.File(['bad'], 'small.jpg')];
  Object.defineProperty($('files'), 'files', {value: files});
  $('files').dispatchEvent(new w.Event('change'));
  assert.match($('upload-confirmation').textContent, /Selected images: 2/);
  assert.equal($('start').disabled, false);
  $('start').click(); await tick();
  assert.equal(ui.calls(), 1);
  $('theme-dark').click();
  assert.equal(w.document.documentElement.dataset.theme, 'dark');
  assert.equal(w.localStorage.getItem('compression-theme'), 'dark');
  change('pl');
  assert.equal($('theme-dark').getAttribute('aria-pressed'), 'true');
  assert.equal($('theme-light').getAttribute('aria-pressed'), 'false');
  assert.equal($('language-pl').getAttribute('aria-pressed'), 'true');
  assert.equal($('theme-dark').getAttribute('aria-label'), 'Ciemny');
  assert.equal(w.document.documentElement.lang, 'pl');
  assert.equal($('start').textContent, 'Rozpocznij analizę');
  assert.equal($('files').disabled, true);
  assert.match($('upload-confirmation').textContent, /Wybrane obrazy: 2/);
  ui.finish();
  for (let i = 0; i < 20 && $('files').disabled; i++) await tick();
  assert.equal($('results').children.length, 2);
  assert.match($('results').textContent, /93,5/);
  assert.match($('results').textContent, /Minimalny rozmiar obrazu/);
  assert.match($('selection').textContent, /Zakończono: 2 \/ 2/);
  assert.match($('histogram').textContent, /Liczba próbek/);
  change('en');
  assert.equal(w.document.documentElement.dataset.theme, 'dark');
  assert.equal($('theme-dark').getAttribute('aria-label'), 'Dark');
  assert.equal($('results').children.length, 2);
  assert.equal(ui.calls(), 2, 'Changing language must not re-run inference');
  assert.match($('results').textContent, /93\.5/);
  assert.match($('results').textContent, /The minimum image size/);
  assert.match($('selection').textContent, /Completed: 2 \/ 2/);
  assert.match($('histogram').textContent, /Number of samples/);
  assert.match($('histogram-note').textContent, /Samples shown: 1/);
  assert.equal(w.localStorage.getItem('compression-language'), 'en');
  const exported = JSON.parse(vm.runInContext('JSON.stringify(exportResults())', context));
  assert.match(exported[1].error, /The minimum image size/);
  assert.equal(exported[0].predicted_quality, 93.5);
  assert.ok(!/[ąćęłńóśźż]/i.test(w.document.body.textContent), 'English UI contains Polish text');
  const rowsBefore = $('results').innerHTML;
  $('theme-light').click();
  assert.equal(w.document.documentElement.dataset.theme, 'light');
  assert.equal($('results').innerHTML, rowsBefore);
  const saved = create('pl', false, 'dark'); await tick();
  assert.equal(saved.w.document.documentElement.dataset.theme, 'dark');
  assert.equal(saved.$('theme-dark').getAttribute('aria-pressed'), 'true');
  assert.equal(saved.w.document.documentElement.lang, 'pl'); saved.dom.window.close();
  const blocked = create(undefined, true); await tick();
  assert.equal(blocked.w.document.documentElement.lang, 'en'); blocked.change('pl');
  blocked.$('theme-dark').click();
  assert.equal(blocked.w.document.documentElement.dataset.theme, 'dark'); blocked.dom.window.close();
  ui.dom.window.close();
  console.log('PASS: English default; complete dictionaries; language and theme switching during and after analysis; retained results; translated errors, exports, histogram, accessibility; saved preferences; unavailable storage.');
})().catch(error => { console.error(error); process.exit(1); });
